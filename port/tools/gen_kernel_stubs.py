"""Generate missing Xbox import implementations from the current runtime."""
import argparse
import json
from pathlib import Path
import re


def main():
    repo = Path(__file__).resolve().parents[2]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--ppc-dir', type=Path, default=repo / 're/ppc')
    parser.add_argument('--runtime', type=Path, default=repo / 'port/src/runtime')
    parser.add_argument('--output', type=Path, default=repo / 'port/src/runtime/kernel_stubs.gen.cpp')
    args = parser.parse_args()
    files = sorted(args.ppc_dir.glob('ppc_recomp.*.cpp'))
    mapping = args.ppc_dir / 'ppc_func_mapping.cpp'
    if mapping.exists(): files.append(mapping)
    if not files: parser.error(f'No generated PPC sources in {args.ppc_dir}')
    if not args.runtime.is_dir(): parser.error(f'Runtime directory does not exist: {args.runtime}')
    # Runtime edits are common; generated import names need rescanning only when
    # their input file metadata changes. Cache stays beside the build output.
    cache = args.output.with_suffix('.imports.json')
    signatures = [[str(path.resolve()), path.stat().st_size, path.stat().st_mtime_ns] for path in files]
    saved = {}
    try: saved = json.loads(cache.read_text())
    except (OSError, ValueError): pass
    if saved.get('sources') == signatures:
        imports = set(saved['imports'])
    else:
        pattern = re.compile(rb'__imp__([A-Za-z0-9_]+)')
        imports = {m.group(1).decode('ascii') for path in files for m in pattern.finditer(path.read_bytes())}
        args.output.parent.mkdir(parents=True, exist_ok=True)
        cache.write_text(json.dumps({'sources': signatures, 'imports': sorted(imports)}, sort_keys=True))
    implementation = re.compile(rb'PPC_FUNC\s*\(\s*__imp__([A-Za-z0-9_]+)\s*\)\s*\{')
    implemented = {m.group(1).decode('ascii') for path in sorted(args.runtime.rglob('*.cpp'))
                   if not path.name.endswith('.gen.cpp') for m in implementation.finditer(path.read_bytes())}
    missing = sorted(name for name in imports if not name.startswith('sub_') and name != '_xstart' and name not in implemented)
    text = '// Generated by gen_kernel_stubs.py; do not edit.\n#include "ppc_recomp_shared.h"\n#include "kernel_trace.h"\n\n'
    text += ''.join(f'PPC_FUNC(__imp__{name}) {{ KernelStub("{name}"); ctx.r3.u64 = 0; }}\n' for name in missing)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text)
    print(f'Generated {len(missing)} missing import stubs ({len(implemented)} runtime implementations)')


if __name__ == '__main__':
    main()
