#include "host_status.h"

namespace host_status {
uint32_t NtStatusToDosError(uint32_t status)
{
    // Guest-visible DOS errors are ABI values, independent of the host's errno
    // or GetLastError. Extend this table when guest imports expose more statuses.
    if ((status & 0x0FFF0000u) == 0x00070000u) return status & 0xFFFFu;
    switch (status)
    {
    case 0x00000000u: return 0;    // STATUS_SUCCESS -> ERROR_SUCCESS
    case 0x00000102u: return 1460; // STATUS_TIMEOUT -> ERROR_TIMEOUT
    case 0x00000103u: return 997;  // STATUS_PENDING -> ERROR_IO_PENDING
    case 0x80000006u: return 18;   // STATUS_NO_MORE_FILES -> ERROR_NO_MORE_FILES
    case 0x80000005u: return 234;  // STATUS_BUFFER_OVERFLOW -> ERROR_MORE_DATA
    case 0xC0000001u: return 31;   // STATUS_UNSUCCESSFUL -> ERROR_GEN_FAILURE
    case 0xC0000002u: return 1;    // STATUS_NOT_IMPLEMENTED -> ERROR_INVALID_FUNCTION
    case 0xC0000008u: return 6;    // STATUS_INVALID_HANDLE -> ERROR_INVALID_HANDLE
    case 0xC000000Du: return 87;   // STATUS_INVALID_PARAMETER -> ERROR_INVALID_PARAMETER
    case 0xC000000Fu: return 2;    // STATUS_NO_SUCH_FILE -> ERROR_FILE_NOT_FOUND
    case 0xC0000011u: return 38;   // STATUS_END_OF_FILE -> ERROR_HANDLE_EOF
    case 0xC0000017u: return 8;    // STATUS_NO_MEMORY -> ERROR_NOT_ENOUGH_MEMORY
    case 0xC0000022u: return 5;    // STATUS_ACCESS_DENIED -> ERROR_ACCESS_DENIED
    case 0xC0000023u: return 122;  // STATUS_BUFFER_TOO_SMALL -> ERROR_INSUFFICIENT_BUFFER
    case 0xC0000024u: return 6;    // STATUS_OBJECT_TYPE_MISMATCH -> ERROR_INVALID_HANDLE
    case 0xC0000033u: return 123;  // STATUS_OBJECT_NAME_INVALID -> ERROR_INVALID_NAME
    case 0xC0000034u: return 2;    // STATUS_OBJECT_NAME_NOT_FOUND -> ERROR_FILE_NOT_FOUND
    case 0xC0000035u: return 183;  // STATUS_OBJECT_NAME_COLLISION -> ERROR_ALREADY_EXISTS
    case 0xC000003Au: return 3;    // STATUS_OBJECT_PATH_NOT_FOUND -> ERROR_PATH_NOT_FOUND
    case 0xC0000043u: return 32;   // STATUS_SHARING_VIOLATION -> ERROR_SHARING_VIOLATION
    case 0xC000004Au: return 156;  // STATUS_SUSPEND_COUNT_EXCEEDED -> ERROR_SIGNAL_REFUSED
    case 0xC0000054u: return 33;   // STATUS_FILE_LOCK_CONFLICT -> ERROR_LOCK_VIOLATION
    case 0xC0000056u: return 5;    // STATUS_DELETE_PENDING -> ERROR_ACCESS_DENIED
    case 0xC000007Fu: return 112;  // STATUS_DISK_FULL -> ERROR_DISK_FULL
    case 0xC000009Au: return 1450; // STATUS_INSUFFICIENT_RESOURCES -> ERROR_NO_SYSTEM_RESOURCES
    case 0xC000009Cu: return 23;   // STATUS_DEVICE_DATA_ERROR -> ERROR_CRC
    case 0xC00000BBu: return 50;   // STATUS_NOT_SUPPORTED -> ERROR_NOT_SUPPORTED
    case 0xC0000103u: return 267;  // STATUS_NOT_A_DIRECTORY -> ERROR_DIRECTORY
    case 0xC0000120u: return 995;  // STATUS_CANCELLED -> ERROR_OPERATION_ABORTED
    case 0xC0000185u: return 1117; // STATUS_IO_DEVICE_ERROR -> ERROR_IO_DEVICE
    default: return 317;           // ERROR_MR_MID_NOT_FOUND
    }
}
}
