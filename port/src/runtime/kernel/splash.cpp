uint32_t g_pixels[W * H];

// One 8x8 glyph at (x, y), scaled x3, 1 byte per row (bit 0 = leftmost).
void Glyph(uint32_t* px, char c, int x, int y, uint32_t color)
{
    if (c < 0x20 || c > 0x7E) c = '?';
    const uint8_t* g = kFont[c - 0x20];
    for (int row = 0; row < 8; ++row)
        for (int col = 0; col < 8; ++col)
            if (g[row] & (1u << col))      // font8x8 LSB-first: bit 0 = leftmost
                for (int sy = 0; sy < 3; ++sy)
                    for (int sx = 0; sx < 3; ++sx)
                    {
                        const int px_ = x + col * 3 + sx, py = y + row * 3 + sy;
                        if (px_ >= 0 && px_ < (int)W && py >= 0 && py < (int)H)
                            px[py * W + px_] = color;
                    }
}

void Text(uint32_t* px, const char* s, int x, int y, uint32_t color)
{
    for (const char* p = s; *p; ++p, x += 8 * 3 + 3)
        Glyph(px, *p, x, y, color);
}

int TextWidth(const char* s) { return int(std::strlen(s)) * (8 * 3 + 3) - 3; }

void Centered(uint32_t* px, const char* s, int y, uint32_t color)
{
    Text(px, s, (int(W) - TextWidth(s)) / 2, y, color);
}

void Render(const char* creditPc, const char* creditPs5)
{
    // Background: deep navy gradient with a faint vignette.
    for (uint32_t y = 0; y < H; ++y)
        for (uint32_t x = 0; x < W; ++x)
        {
            const uint32_t t = y * 255u / (H - 1);
            const uint32_t r = 16 + (10 * t >> 8), g_ = 14 + (8 * t >> 8), b = 26 + (16 * t >> 8);
            g_pixels[y * W + x] = 0xFF000000u | (b << 16) | (g_ << 8) | r;
        }
    // Accent rule under the title block.
    for (uint32_t x = W / 2 - 220; x < W / 2 + 220; ++x)
        for (uint32_t y = 328; y < 332; ++y)
            g_pixels[y * W + x] = 0xFFB02A1Cu;  // BGRX 0xXXRRGGBB: tekken red, subtle

    // Layout: title, subtitle, rule, credits, footer.
    Centered(g_pixels, kLine1, 150, 0xFFF8F8F8u);
    Centered(g_pixels, kLine2, 240, 0xFFB0B0B8u);
    Centered(g_pixels, creditPs5, 380, 0xFFE8E8EEu);   // tu nombre primero
    Centered(g_pixels, creditPc, 430, 0xFFE8E8EEu);
    Centered(g_pixels, kFooter, 650, 0xFF606068u);
}

