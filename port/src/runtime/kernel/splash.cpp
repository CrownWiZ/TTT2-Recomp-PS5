bool Active()
{
    static const uint64_t start = [] {
        // First call happens at the first present the runtime can make; the
        // splash window runs from there.
        using namespace std::chrono;
        return uint64_t(duration_cast<milliseconds>(steady_clock::now().time_since_epoch()).count());
    }();
    static const uint64_t ms = [] {
        const char* e = std::getenv("TTT2_SPLASH_MS");
        return e ? uint64_t(std::strtoull(e, nullptr, 0)) : 3500ull;
    }();
    if (!ms) return false;
    using namespace std::chrono;
    const uint64_t now = uint64_t(duration_cast<milliseconds>(steady_clock::now().time_since_epoch()).count());
    if (now - start >= ms) return false;
    static const bool ready = [] {
        // TTT2_SPLASH_CREDITS="pc line|ps5 line" overrides the two credit lines.
        const char* env = std::getenv("TTT2_SPLASH_CREDITS");
        const char* creditPc = kCreditPc;
        const char* creditPs5 = kCreditPs5;
        static char credits[256];
        if (env && *env)
        {
            std::snprintf(credits, sizeof credits, "%s", env);
            if (char* sep = std::strchr(credits, '|'))
            {
                *sep = 0;
                creditPs5 = sep + 1;
            }
            creditPc = credits;
        }
        Render(creditPc, creditPs5);
        return true;
    }();
    (void)ready;
    return true;
}

